CREATE TABLE IF NOT EXISTS purchase_upload_batch (
    UPLOAD_BATCH_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '업로드 배치 ID',
    PURCHASE_YEAR INT NOT NULL COMMENT '구매실적 연도',
    PURCHASE_MONTH INT NOT NULL COMMENT '구매실적 월',
    ORIGINAL_FILENAME VARCHAR(255) NOT NULL COMMENT '업로드 원본 파일명',
    FILE_SHA256 CHAR(64) NOT NULL COMMENT '파일 SHA-256 해시',
    UPLOAD_STATUS VARCHAR(20) NOT NULL DEFAULT 'CURRENT' COMMENT '업로드 상태(CURRENT/REPLACED)',
    PLAN_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 계획 금액(백만원)',
    ACTUAL_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 실적 금액(백만원)',
    SUMMARY_ROW_COUNT INT NOT NULL DEFAULT 0 COMMENT '첫 번째 시트에서 가져온 요약 행 수',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    CREATED_BY BIGINT NULL COMMENT '생성자 사용자 ID',
    UPDATED_AT DATETIME NULL COMMENT '수정일시',
    UPDATED_BY BIGINT NULL COMMENT '수정자 사용자 ID',
    DELETED_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '삭제 여부',
    DELETED_AT DATETIME NULL COMMENT '삭제일시',
    DELETED_BY BIGINT NULL COMMENT '삭제자 사용자 ID',
    PRIMARY KEY (UPLOAD_BATCH_ID),
    INDEX IDX_PURCHASE_BATCH_YEAR_MONTH (PURCHASE_YEAR, PURCHASE_MONTH),
    INDEX IDX_PURCHASE_BATCH_HASH (FILE_SHA256),
    INDEX IDX_PURCHASE_BATCH_STATUS (UPLOAD_STATUS, DELETED_YN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
  COMMENT='구매실적 엑셀 업로드 이력';

CREATE TABLE IF NOT EXISTS purchase_month_snapshot (
    SNAPSHOT_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '월별 현재 자료 ID',
    PURCHASE_YEAR INT NOT NULL COMMENT '구매실적 연도',
    PURCHASE_MONTH INT NOT NULL COMMENT '구매실적 월',
    CURRENT_UPLOAD_BATCH_ID BIGINT NOT NULL COMMENT '현재 반영된 업로드 배치 ID',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    CREATED_BY BIGINT NULL COMMENT '생성자 사용자 ID',
    UPDATED_AT DATETIME NULL COMMENT '수정일시',
    UPDATED_BY BIGINT NULL COMMENT '수정자 사용자 ID',
    DELETED_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '삭제 여부',
    DELETED_AT DATETIME NULL COMMENT '삭제일시',
    DELETED_BY BIGINT NULL COMMENT '삭제자 사용자 ID',
    PRIMARY KEY (SNAPSHOT_ID),
    CONSTRAINT UK_PURCHASE_MONTH UNIQUE (PURCHASE_YEAR, PURCHASE_MONTH),
    CONSTRAINT FK_PURCHASE_SNAPSHOT_BATCH FOREIGN KEY (CURRENT_UPLOAD_BATCH_ID)
        REFERENCES purchase_upload_batch (UPLOAD_BATCH_ID),
    INDEX IDX_PURCHASE_SNAPSHOT_BATCH (CURRENT_UPLOAD_BATCH_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
  COMMENT='연월별 구매실적 현재 자료 포인터';

CREATE TABLE IF NOT EXISTS purchase_category (
    PURCHASE_CATEGORY_ID BIGINT NOT NULL AUTO_INCREMENT COMMENT '구매 카테고리 실적 ID',
    UPLOAD_BATCH_ID BIGINT NOT NULL COMMENT '업로드 배치 ID',
    SOURCE_ROW_NO INT NOT NULL COMMENT '첫 번째 시트의 원본 행 번호',
    CATEGORY_NAME VARCHAR(100) NOT NULL COMMENT '첫 번째 시트의 구매 구분',
    PREVIOUS_ACTUAL_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '전월 실적 합계(백만원)',
    PLAN_FOREIGN_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 외자 계획 금액(백만원)',
    PLAN_DOMESTIC_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 내자 계획 금액(백만원)',
    PLAN_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 계획 합계(백만원)',
    ACTUAL_FOREIGN_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 외자 실적 금액(백만원)',
    ACTUAL_DOMESTIC_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 내자 실적 금액(백만원)',
    ACTUAL_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '당월 실적 합계(백만원)',
    PLAN_VARIANCE_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '계획 대비 증감액(백만원)',
    PREVIOUS_MONTH_VARIANCE_AMOUNT DECIMAL(24,10) NOT NULL DEFAULT 0 COMMENT '전월 대비 증감액(백만원)',
    PLAN_VARIANCE_REASON TEXT NULL COMMENT '계획 대비 증감 사유',
    PREVIOUS_MONTH_VARIANCE_REASON TEXT NULL COMMENT '전월 대비 증감 사유',
    CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    CREATED_BY BIGINT NULL COMMENT '생성자 사용자 ID',
    UPDATED_AT DATETIME NULL COMMENT '수정일시',
    UPDATED_BY BIGINT NULL COMMENT '수정자 사용자 ID',
    DELETED_YN CHAR(1) NOT NULL DEFAULT 'N' COMMENT '삭제 여부',
    DELETED_AT DATETIME NULL COMMENT '삭제일시',
    DELETED_BY BIGINT NULL COMMENT '삭제자 사용자 ID',
    PRIMARY KEY (PURCHASE_CATEGORY_ID),
    CONSTRAINT FK_PURCHASE_CATEGORY_BATCH FOREIGN KEY (UPLOAD_BATCH_ID)
        REFERENCES purchase_upload_batch (UPLOAD_BATCH_ID),
    INDEX IDX_PURCHASE_CATEGORY_BATCH_ROW (UPLOAD_BATCH_ID, SOURCE_ROW_NO),
    INDEX IDX_PURCHASE_CATEGORY_NAME (CATEGORY_NAME),
    INDEX IDX_PURCHASE_CATEGORY_DELETED (DELETED_YN)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci
  COMMENT='구매실적 첫 번째 시트 요약 카테고리';
